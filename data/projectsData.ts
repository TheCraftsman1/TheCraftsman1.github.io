export const getProjectById = (id: string): ProjectItem | undefined => {
  return projects.find((p) => p.id === id);
};

export const getAdjacentProjects = (id: string): { prev: ProjectItem; next: ProjectItem } => {
  const idx = projects.findIndex((p) => p.id === id);
  const safeIdx = idx === -1 ? 0 : idx;
  const prev = safeIdx > 0 ? projects[safeIdx - 1] : projects[projects.length - 1];
  const next = safeIdx < projects.length - 1 ? projects[safeIdx + 1] : projects[0];
  return { prev, next };
};
